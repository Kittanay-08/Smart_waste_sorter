def analyze_waste_image_gemini(image_bytes: bytes, api_key: str = None) -> list[dict] | None:
    """
    วิเคราะห์รูปภาพขยะด้วย Google Gemini 1.5 Flash Vision
    ตรวจจับและจำแนกได้ทุกวัตถุ ทุกประเภท (หลอด, แก้ว, ซองขนม, กล่อง, ขยะทั่วไป ฯลฯ)
    """
    key = (api_key or os.environ.get("GEMINI_API_KEY", "")).strip()
    if not key:
        return None

    import base64
    b64_img = base64.b64encode(image_bytes).decode("utf-8")
    
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={key}"
    prompt_text = (
        "คุณคือระบบ AI ผู้เชี่ยวชาญด้านการคัดแยกขยะอัจฉริยะ (Smart Waste Sorter) "
        "จงวิเคราะห์ภาพนี้ว่ามีขยะหรือสิ่งของอะไรบ้าง โดยเฉพาะอย่างยิ่ง: หลอดดูดน้ำ, แก้วน้ำพลาสติก, ถ้วย, ขวด, กล่องกระดาษ, ซองขนม, ถุงพลาสติก, เศษอาหาร, ขยะอันตราย, เครื่องเขียน หรือขยะทั่วไป "
        "ให้ตอบกลับเป็น JSON array เท่านั้น (ห้ามใส่ markdown ```json หรือข้อความอื่น) ตัวอย่างรูปแบบ:\n"
        "[\n"
        "  {\n"
        "    \"item_name\": \"หลอดดูดน้ำพลาสติก\",\n"
        "    \"class_name\": \"straw\",\n"
        "    \"category\": \"general\",\n"
        "    \"bin_name\": \"ถังสีน้ำเงิน (ขยะทั่วไป)\",\n"
        "    \"confidence\": 0.95,\n"
        "    \"detail\": \"หลอดพลาสติกใช้แล้วทิ้ง\",\n"
        "    \"advice\": \"ทิ้งลงถังสีน้ำเงิน (ขยะทั่วไป) เนื่องจากมีขนาดเล็กไม่เข้าสู่กระบวนการรีไซเคิล\",\n"
        "    \"box\": [100, 100, 900, 900]\n"
        "  }\n"
        "]\n"
        "หมายเหตุ: category ต้องเป็นหนึ่งใน 'recyclable', 'general', 'organic', 'hazardous' "
        "และกล่องพิกัด box คือ [ymin, xmin, ymax, xmax] ในอัตราส่วน 0-1000"
    )
    
    payload = {
        "contents": [
            {
                "parts": [
                    {"text": prompt_text},
                    {
                        "inline_data": {
                            "mime_type": "image/jpeg",
                            "data": b64_img
                        }
                    }
                ]
            }
        ],
        "generationConfig": {
            "temperature": 0.2,
            "maxOutputTokens": 1024
        }
    }
    
    try:
        req = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"}
        )
        with urllib.request.urlopen(req, timeout=12) as response:
            res_data = json.loads(response.read().decode("utf-8"))
            candidates = res_data.get("candidates", [])
            if candidates:
                raw_text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
                raw_text = re.sub(r"^```json\s*", "", raw_text.strip(), flags=re.MULTILINE)
                raw_text = re.sub(r"^```\s*", "", raw_text.strip(), flags=re.MULTILINE)
                parsed = json.loads(raw_text)
                if isinstance(parsed, list) and len(parsed) > 0:
                    return parsed
    except Exception as e:
        print(f"[Gemini Vision Error]: {e}")
    return None

