def call_gemini_api(prompt: str, api_key: str) -> str | None:
    """เรียก Google Gemini 1.5/2.0 API เพื่อตอบคำถามทุกเรื่องได้อย่างอัจฉริยะ (ถ้ามี API Key)"""
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"
    payload = {
        "contents": [
            {
                "parts": [
                    {
                        "text": (
                            "คุณคือผู้ช่วย AI อัจฉริยะรอบรู้ประจำระบบ Smart Waste Sorter "
                            "คุณสามารถตอบคำถามได้ทุกเรื่อง ทุกหัวข้ออย่างสุภาพ ชัดเจน และถูกต้องเป็นภาษาไทย "
                            "หากเป็นคำถามเรื่องขยะ ให้ระบุถังขยะ 4 สีตามมาตรฐานไทย (เขียว=อินทรีย์, เหลือง=รีไซเคิล, น้ำเงิน=ทั่วไป, แดง=อันตราย) พร้อมวิธีจัดการ "
                            "หากเป็นคำถามทั่วไป (วิทยาศาสตร์, เทคโนโลยี, การเรียน, ชีวิตประจำวัน ฯลฯ) ให้ตอบอย่างเป็นประโยชน์และเข้าใจง่าย\n\n"
                            f"คำถามของผู้ใช้: {prompt}"
                        )
                    }
                ]
            }
        ],
        "generationConfig": {
            "temperature": 0.4,
            "maxOutputTokens": 800
        }
    }
    try:
        req = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"}
        )
        with urllib.request.urlopen(req, timeout=10) as response:
            res_data = json.loads(response.read().decode("utf-8"))
            candidates = res_data.get("candidates", [])
            if candidates:
                parts = candidates[0].get("content", {}).get("parts", [])
                if parts:
                    return parts[0].get("text", "").strip()
    except Exception as e:
        print(f"[AI Assistant] Gemini API Error: {e}")
    return None


def search_wikipedia_th(topic: str) -> tuple[str | None, str | None]:
    """ค้นหาข้อมูลสารานุกรมไทยจาก Wikipedia REST API แบบเรียลไทม์"""
    clean = re.sub(r'(คืออะไร|คือใคร|หมายถึงอะไร|อย่างไร|ทิ้งไหน|ช่วยบอกหน่อย|ประวัติ)', '', topic).strip()
    if not clean:
        clean = topic.strip()
    encoded = urllib.parse.quote(clean)

    # 1. ลองดึงสรุปโดยตรง
    url = f"https://th.wikipedia.org/api/rest_v1/page/summary/{encoded}"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "SmartWasteSorterBot/2.0"})
        with urllib.request.urlopen(req, timeout=5) as r:
            data = json.loads(r.read().decode("utf-8"))
            extract = data.get("extract")
            if extract and data.get("type") != "disambiguation":
                return data.get("title"), extract
    except Exception:
        pass

    # 2. หากไม่พบ ลองใช้ OpenSearch ค้นหาหัวข้อที่ใกล้เคียง
    search_url = f"https://th.wikipedia.org/w/api.php?action=opensearch&search={encoded}&limit=1&format=json"
    try:
        req = urllib.request.Request(search_url, headers={"User-Agent": "SmartWasteSorterBot/2.0"})
        with urllib.request.urlopen(req, timeout=5) as r:
            s_data = json.loads(r.read().decode("utf-8"))
            if len(s_data) > 1 and s_data[1]:
                matched_title = s_data[1][0]
                m_enc = urllib.parse.quote(matched_title)
                m_url = f"https://th.wikipedia.org/api/rest_v1/page/summary/{m_enc}"
                req2 = urllib.request.Request(m_url, headers={"User-Agent": "SmartWasteSorterBot/2.0"})
                with urllib.request.urlopen(req2, timeout=5) as r2:
                    d2 = json.loads(r2.read().decode("utf-8"))
                    extract = d2.get("extract")
                    if extract:
                        return d2.get("title"), extract
    except Exception:
        pass

    return None, None


def try_calculate_math(q: str) -> str | None:
    """คำนวณสูตรคณิตศาสตร์พื้นฐานได้อย่างปลอดภัย"""
    clean = re.sub(r'[^0-9+\-*/().^]', '', q.replace('x', '*').replace('X', '*').replace('÷', '/'))
    if clean and any(op in clean for op in '+-*/') and not re.search(r'[a-zA-Z_]', clean):
        try:
            val = eval(clean, {"__builtins__": None}, {})
            if isinstance(val, (int, float)):
                return f"🧮 **ผลลัพธ์การคำนวณ:**\n`{clean}` = **{val:g}**"
        except Exception:
            pass
    return None


